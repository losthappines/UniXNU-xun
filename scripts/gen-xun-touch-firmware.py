#!/usr/bin/env python3
"""Generate build/native-touch/XunTouchFirmware.c from untracked vendor touch blobs."""
import hashlib
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
CACHE_DIR = ROOT / '.cache' / 'firmware' / 'xun'
OUT_FILE = ROOT / 'build' / 'native-touch' / 'XunTouchFirmware.c'

FIRMWARE_SPECS = [
    (
        'native_xun_fw_boe',
        CACHE_DIR / 'focaltech_ts_fw_boe_ft8203.bin',
        '3a528016614ddfaa33c0e38fb2b2c91aebed8711f4a9dd4f31f333c8b8b3162e',
    ),
    (
        'native_xun_fw_huaxing',
        CACHE_DIR / 'focaltech_ts_fw_huaxing_ft8203.bin',
        '0a7d49735fca986be6263134c6c4891075da9add347a2c6008eb8433cd97fa38',
    ),
    (
        'native_xun_fw_tianma',
        CACHE_DIR / 'novatek_ts_fw_tianma.bin',
        '1bb9ca434178a38b994bf0003ba23d8371514bcecb9a4e3f3b3bd553d952bd22',
    ),
]


def format_array(symbol: str, data: bytes) -> str:
    if not data:
        return (
            f'const uint8_t {symbol}[1] = {{0}};\n'
            f'const uint32_t {symbol}_size = 0u;\n'
        )
    lines = [f'const uint8_t {symbol}[{len(data)}] = {{']
    for offset in range(0, len(data), 16):
        chunk = ', '.join(f'0x{b:02x}' for b in data[offset:offset + 16])
        lines.append(f'    {chunk},')
    lines.append('};')
    lines.append(f'const uint32_t {symbol}_size = {len(data)}u;')
    return '\n'.join(lines) + '\n'


def main() -> int:
    strict = '--require-blobs' in sys.argv[1:] or os.environ.get('GITHUB_ACTIONS') == 'true'
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    sections = ['/* Generated by scripts/gen-xun-touch-firmware.py; do not edit. */\n#include <stdint.h>\n\n']
    missing = []
    for symbol, path, expected_sha256 in FIRMWARE_SPECS:
        if path.is_file():
            data = path.read_bytes()
            actual_sha256 = hashlib.sha256(data).hexdigest()
            if actual_sha256 != expected_sha256:
                raise SystemExit(
                    f'{path.name} sha256 mismatch: {actual_sha256} != {expected_sha256}'
                )
            print(f'Staged {symbol} ({len(data)} bytes, sha256 {actual_sha256[:12]}...)')
            sections.append(format_array(symbol, data))
        else:
            missing.append(str(path))
            print(f'Warning: {path} missing; emitting empty {symbol} stub')
            sections.append(format_array(symbol, b''))
    if strict and missing:
        raise SystemExit(f'Missing required firmware blobs: {", ".join(missing)}')
    OUT_FILE.write_text('\n'.join(sections), encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
